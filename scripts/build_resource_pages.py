#!/usr/bin/env python3
"""Generate the resource-list pages from the canonical CSV.

The CSV in data/ is the single source of truth for the 188 resources. Edit it
(or data/categories.json for section titles and intro text), then run:

    python scripts/build_resource_pages.py

This rewrites every docs/resources/<slug>.md and refreshes the category table
inside docs/resources/index.md between the BEGIN/END markers. CI re-runs this
and fails if the committed pages are stale, so the CSV and the site can never
disagree.
"""
from __future__ import annotations

import json
import pathlib
import sys

import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
CSV = ROOT / "data" / "neuroscience_data_resources.csv"
CATS = ROOT / "data" / "categories.json"
OUT = ROOT / "docs" / "resources"

COLUMNS = ["Resource", "Host (Region)", "Species", "Data type / technique",
           "Level", "Access", "What it is"]

BEGIN = "<!-- BEGIN:category-index (generated by scripts/build_resource_pages.py) -->"
END = "<!-- END:category-index -->"


def esc(text: str) -> str:
    """Make a cell safe for a GitHub-flavoured markdown table."""
    return str(text).replace("|", "&#124;").replace("\n", "<br>").strip()


def row_to_cells(row: pd.Series) -> list[str]:
    name = esc(row["Resource"])
    url = str(row["URL"]).strip()
    resource = f"**[{name}]({url})**" if url and url.lower() != "nan" else f"**{name}**"
    host = f"{esc(row['Host'])} ({esc(row['Region'])})"
    return [resource, host, esc(row["Species"]), esc(row["Technique"]),
            esc(row["Level"]), esc(row["Access"]), esc(row["Description"])]


def render_table(block: pd.DataFrame) -> str:
    lines = ["| " + " | ".join(COLUMNS) + " |",
             "|" + "---|" * len(COLUMNS)]
    for _, row in block.iterrows():
        lines.append("| " + " | ".join(row_to_cells(row)) + " |")
    return "\n".join(lines)


def main() -> int:
    df = pd.read_csv(CSV)
    meta = json.loads(CATS.read_text())

    known = {c["title"] for c in meta}
    unknown = sorted(set(df["Category"]) - known)
    if unknown:
        sys.exit(f"Categories in the CSV with no entry in categories.json: {unknown}")

    OUT.mkdir(parents=True, exist_ok=True)
    index_rows = []

    for cat in meta:
        block = df[df["Category"] == cat["title"]]
        if block.empty:
            sys.exit(f"No resources found for category {cat['title']!r}")
        page = OUT / f"{cat['slug']}.md"
        page.write_text(
            f"# {cat['title']}\n\n"
            f"{cat['intro']}\n\n"
            f"*{len(block)} resources. Generated from "
            f"[`data/neuroscience_data_resources.csv`](../about/contributing.md) — "
            f"edit the CSV, not this page.*\n\n"
            f"{render_table(block)}\n"
        )
        index_rows.append(f"| [{cat['title']}]({cat['slug']}.md) | {len(block)} |")

    idx = OUT / "index.md"
    text = idx.read_text()
    table = "\n".join(["| Category | Resources |", "|---|---|", *index_rows,
                       f"| **Total** | **{len(df)}** |"])
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    idx.write_text(f"{head}{BEGIN}\n\n{table}\n\n{END}{tail}")

    print(f"Wrote {len(meta)} category pages covering {len(df)} resources.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
